//! Theme presets. The seeds are Zeron's built-in dark themes (MIT, see
//! `THIRD_PARTY_NOTICES.md`); [`super::Palette::from_seed`] derives every
//! other token from these eleven colors.

pub struct ThemeSeed {
    pub id: &'static str,
    pub name: &'static str,
    pub bg: u32,
    pub shell: u32,
    pub raised: u32,
    pub card: u32,
    pub text: u32,
    pub muted: u32,
    pub faint: u32,
    pub accent: u32,
    pub danger: u32,
    pub warning: u32,
    pub success: u32,
}

pub const DEFAULT_THEME: &str = "forge";

macro_rules! seeds {
    ($($id:literal $name:literal $bg:literal $shell:literal $raised:literal $card:literal
       $text:literal $muted:literal $faint:literal $accent:literal $danger:literal
       $warning:literal $success:literal;)*) => {
        pub const THEMES: &[ThemeSeed] = &[$(ThemeSeed {
            id: $id, name: $name, bg: $bg, shell: $shell, raised: $raised, card: $card,
            text: $text, muted: $muted, faint: $faint, accent: $accent, danger: $danger,
            warning: $warning, success: $success,
        }),*];
    };
}

