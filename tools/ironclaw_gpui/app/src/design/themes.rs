impl ThemeSeed {
    pub fn is_light(&self) -> bool {
        // Relative luminance of the background, coarse but enough to sort.
        let (r, g, b) = (self.bg >> 16 & 0xff, self.bg >> 8 & 0xff, self.bg & 0xff);
        (r * 299 + g * 587 + b * 114) / 1000 > 128
    }
}

